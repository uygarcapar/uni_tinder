const RECENT_KEY = "chat.emoji.recent";
const RECENT_LIMIT = 30;

/**
 * Son kullanılanlar app-prefs'te (logout'ta silinmeyen küçük tercih deposu).
 * Kullanıcıya özel DEĞİL: cihaz başına tek liste — bu ekranda kişiselleştirme
 * beklentisi yok, tek anahtar sözlüğü sade tutuyor.
 */
export function readRecentEmojis(): string[] {
  const raw = appPrefs.getString(RECENT_KEY);
  if (!raw) return [];
  try {
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed)
      ? parsed.filter((e): e is string => typeof e === "string").slice(0, RECENT_LIMIT)
      : [];
  } catch {
    return [];
  }
}

export function pushRecentEmoji(emoji: string): void {
  const next = [emoji, ...readRecentEmojis().filter((e) => e !== emoji)].slice(
    0,
    RECENT_LIMIT,
  );
  appPrefs.set(RECENT_KEY, JSON.stringify(next));
}
